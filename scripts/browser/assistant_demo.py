"""Run against the local dev server with the documented provider fixture."""
from playwright.sync_api import sync_playwright, expect
import secrets
with sync_playwright() as pw:
    b = pw.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox'])
    for w, h in [(1440, 900), (390, 844)]:
        p = b.new_page(viewport=dict(width=w, height=h))
        p.set_default_timeout(20000)

        def layout():
            assert p.evaluate('document.documentElement.scrollWidth <= innerWidth')
        email = 'browser-' + secrets.token_hex(6) + '@example.test'
        password = secrets.token_hex(14)
        p.goto('http://localhost:3000/register')
        p.get_by_role('link', name='Sign in').click()
        p.get_by_role('link', name='Create an account').click()
        p.get_by_role('button', name='Create account').click()
        assert p.locator('input:invalid').count() > 0
        layout()
        for name, value in [('name', 'Acceptance Tester'), ('email', email), ('password', password)]:
            p.locator('[name=' + name + ']:visible').fill(value)
        p.get_by_role('button', name='Create account').click()
        p.wait_for_url('**/onboarding')
        p.locator('[name=businessName]').fill('Browser acceptance')
        p.locator('[name=locationName]').fill('Test location')
        p.locator('select').select_option(index=1)
        layout()
        p.get_by_role('button', name='Create workspace').click()
        p.wait_for_url('**/dashboard')
        p.get_by_role('link', name='Overview').click()
        expect(p.get_by_text('Test location', exact=True).first).to_be_visible()
        layout()
        p.get_by_role('link', name='AI assistants').click()
        p.get_by_label('Load template').select_option('example')
        p.get_by_role('button', name='Save new draft version').click()
        expect(p.get_by_role('button', name='Publish and enable')).to_be_disabled()
        p.get_by_label('Customer name').fill('Demo tester')
        p.get_by_role('button', name='Start version test').click()
        p.get_by_label('Message', exact=True).fill('When are you open?')
        p.get_by_role('button', name='Send', exact=True).click()
        expect(p.get_by_text('Open Monday to Friday from 9 am to 5 pm.', exact=False).filter(visible=True).last).to_be_visible(timeout=25000)
        expect(p.get_by_role('button', name='Publish and enable')).to_be_enabled()
        p.reload()
        p.get_by_label('Message', exact=True).fill('Confirm an appointment')
        p.get_by_role('button', name='Send', exact=True).click()
        expect(p.get_by_text('Awaiting staff follow-up')).to_be_visible()
        thread = p.url
        p.get_by_role('button', name='Publish and enable').click()
        expect(p.get_by_text('Enabled · Published version 1')).to_be_visible()
        p.get_by_role('button', name='Disable', exact=True).click()
        expect(p.get_by_text('Disabled · Published version 1')).to_be_visible()
        p.get_by_role('link', name='Workspace overview').click()
        p.get_by_role('link', name='Staff handoffs').click()
        inbox = p.url
        expect(p.get_by_text('Test conversation', exact=False)).to_be_visible()
        p.get_by_role('button', name='Assign to me').click()
        expect(p.get_by_role('button', name='Release assignment')).to_be_visible()
        p.reload()
        p.get_by_role('button', name='Release assignment').click()
        expect(p.get_by_text('Unassigned', exact=True)).to_be_visible()
        layout()
        p.get_by_role('link', name='Demo tester').click()
        expect(p.get_by_text('Awaiting staff follow-up')).to_be_visible()
        outsider = b.new_page()
        outsider.goto('http://localhost:3000/register')
        outsider.locator('input[name=name]:visible').fill('Outsider')
        outsider.locator('input[name=email]:visible').fill('outside-' + secrets.token_hex(8) + '@example.test')
        outsider.locator('input[name=password]:visible').fill(secrets.token_hex(12))
        outsider.get_by_role('button', name='Create account').click()
        outsider.wait_for_url('**/onboarding')
        outsider.goto(thread)
        expect(outsider.get_by_text('404', exact=True)).to_be_visible()
        assert 'Demo tester' not in outsider.locator('body').inner_text()
        outsider.goto(inbox)
        expect(outsider.get_by_text('404', exact=True)).to_be_visible()
        outsider.close()
        layout()
        p.close()
        print(w, h, 'assistant demo passed', flush=True)
    b.close()
